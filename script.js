const root = document.documentElement;
const languageButton = document.querySelector('.language-toggle');
const themeButton = document.querySelector('.theme-toggle');
const themeIcon = document.querySelector('.theme-icon');
const navToggle = document.querySelector('.nav-toggle');
const navLinks = document.querySelector('.nav-links');

let language = localStorage.getItem('portfolio-language') || 'fr';
let theme = localStorage.getItem('portfolio-theme') || (window.matchMedia('(prefers-color-scheme: light)').matches ? 'light' : 'dark');

function applyLanguage(lang) {
  language = lang;
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(node => {
    const value = translations[lang][node.dataset.i18n];
    if (value) node.textContent = value;
  });
  languageButton.textContent = lang === 'fr' ? 'EN' : 'FR';
  languageButton.setAttribute('aria-label', lang === 'fr' ? 'Switch website to English' : 'Passer le site en français');
  localStorage.setItem('portfolio-language', lang);
}

function applyTheme(nextTheme) {
  theme = nextTheme;
  root.dataset.theme = theme;
  themeIcon.textContent = theme === 'dark' ? '☼' : '☾';
  document.querySelector('meta[name="theme-color"]').setAttribute('content', theme === 'dark' ? '#070b14' : '#f5f7fb');
  localStorage.setItem('portfolio-theme', theme);
}

applyLanguage(language);
applyTheme(theme);

languageButton.addEventListener('click', () => applyLanguage(language === 'fr' ? 'en' : 'fr'));
themeButton.addEventListener('click', () => applyTheme(theme === 'dark' ? 'light' : 'dark'));

navToggle.addEventListener('click', () => {
  const open = navLinks.classList.toggle('open');
  navToggle.setAttribute('aria-expanded', String(open));
});

document.querySelectorAll('.nav-links a').forEach(link => link.addEventListener('click', () => {
  navLinks.classList.remove('open');
  navToggle.setAttribute('aria-expanded', 'false');
}));

const revealElements = document.querySelectorAll(".reveal");

const observer = new IntersectionObserver(
  (entries) => {
    entries.forEach((entry) => {
      entry.target.classList.toggle(
        "visible",
        entry.isIntersecting
      );
    });
  },
  {
    threshold: 0.15,

    rootMargin: "2% 0px -5% 0px"
  }
);

revealElements.forEach((element) => {
  observer.observe(element);
});

// Doit correspondre à la durée CSS : 350 ms
const FILTER_TRANSITION_MS = window.matchMedia(
  '(prefers-reduced-motion: reduce)'
).matches ? 0 : 350;

const filters = document.querySelectorAll('.filter');
const projects = document.querySelectorAll(
  '.projects-grid > .project-card'
);

let filterTimeout = null;

function projectMatchesFilter(project, category) {
  const categories = (project.dataset.category || '')
    .split(/\s+/)
    .filter(Boolean);

  return category === 'all' || categories.includes(category);
}

function filterProjects(category) {
  // Annule une éventuelle animation précédente
  window.clearTimeout(filterTimeout);

  // Cartes actuellement affichées
  const visibleProjects = Array.from(projects).filter(project => {
    return !project.classList.contains('hidden');
  });

  // Phase 1 : animation de sortie
  visibleProjects.forEach(project => {
    project.classList.remove('filter-enter');
    project.classList.add('filter-exit');
  });

  filterTimeout = window.setTimeout(() => {
    const projectsToShow = [];

    projects.forEach(project => {
      const shouldShow = projectMatchesFilter(project, category);

      project.classList.remove('filter-exit');
      project.classList.toggle('hidden', !shouldShow);

      if (shouldShow) {
        /*
         * "visible" évite un conflit avec ton système
         * IntersectionObserver/reveal.
         */
        project.classList.add('visible');
        project.classList.add('filter-enter');
        projectsToShow.push(project);
      } else {
        project.classList.remove('filter-enter');
      }
    });

    // Force le navigateur à enregistrer l'état initial
    // avant de lancer l'animation d'entrée.
    document.querySelector('.projects-grid').offsetHeight;

    window.requestAnimationFrame(() => {
      projectsToShow.forEach(project => {
        project.classList.remove('filter-enter');
      });
    });
  }, FILTER_TRANSITION_MS);
}

filters.forEach(filter => {
  filter.addEventListener('click', () => {
    // Évite de relancer inutilement le filtre actif
    if (filter.classList.contains('active')) return;

    filters.forEach(button => {
      const isActive = button === filter;

      button.classList.toggle('active', isActive);
      button.setAttribute('aria-pressed', String(isActive));
    });

    filterProjects(filter.dataset.filter);
  });
});


